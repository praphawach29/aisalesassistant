-- Create category_expertise table
CREATE TABLE public.category_expertise (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  category TEXT NOT NULL,
  expertise_name TEXT NOT NULL,
  expertise_prompt TEXT NOT NULL,
  selling_tips TEXT,
  terminology TEXT,
  common_questions TEXT,
  store_type TEXT DEFAULT 'general',
  is_active BOOLEAN DEFAULT true,
  is_system BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Create unique constraint on category + store_type
CREATE UNIQUE INDEX idx_category_expertise_unique ON public.category_expertise (category, store_type);

-- Enable RLS
ALTER TABLE public.category_expertise ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Anyone can read category expertise"
  ON public.category_expertise FOR SELECT
  USING (true);

-- Only admins can modify
CREATE POLICY "Admins can insert category expertise"
  ON public.category_expertise FOR INSERT
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    )
  );

CREATE POLICY "Admins can update category expertise"
  ON public.category_expertise FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM public.user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    )
  );

CREATE POLICY "Admins can delete category expertise"
  ON public.category_expertise FOR DELETE
  USING (
    EXISTS (
      SELECT 1 FROM public.user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    )
  );

-- Add columns to ai_settings
ALTER TABLE public.ai_settings
ADD COLUMN IF NOT EXISTS default_store_type TEXT DEFAULT 'auto',
ADD COLUMN IF NOT EXISTS use_auto_detect BOOLEAN DEFAULT true;

-- Create trigger for updated_at
CREATE TRIGGER update_category_expertise_updated_at
  BEFORE UPDATE ON public.category_expertise
  FOR EACH ROW
  EXECUTE FUNCTION public.update_updated_at_column();

